export function EmojiPicker({ onEmojiSelect, onClose }: EmojiPickerProps) {
  const [selectedCategory, setSelectedCategory] = useState("Smileys & People")
  const [searchQuery, setSearchQuery] = useState("")

  const filteredEmojis = emojiCategories[selectedCategory as keyof typeof emojiCategories].filter(emoji =>
    searchQuery === "" || emoji.includes(searchQuery)
  )

  const handleEmojiClick = (emoji: string) => {
    onEmojiSelect(emoji)
    onClose?.()
  }

  return (
    <div className="w-80 h-96 bg-white border border-gray-200 rounded-lg shadow-lg">
      <div className="p-4 border-b border-gray-200">
        <div className="relative">
          <Search className="absolute left-3 top-1/2 transform -translate-y-1/2 h-4 w-4 text-gray-400" />
          <Input
            placeholder="Search emojis..."
            value={searchQuery}
            onChange={(e) => setSearchQuery(e.target.value)}
            className="pl-10"
          />
        </div>
      </div>
      
      <div className="flex h-80">
        {/* Category Sidebar */}
        <div className="w-20 border-r border-gray-200 bg-gray-50">
          <ScrollArea className="h-full">
            <div className="p-2 space-y-1">
              {Object.keys(emojiCategories).map((category) => (
                <Button
                  key={category}
                  variant={selectedCategory === category ? "default" : "ghost"}
                  size="sm"
                  className="w-full h-8 p-0 text-xs justify-center"
                  onClick={() => setSelectedCategory(category)}
                >
                  {category === "Smileys & People" && <Smile className="h-4 w-4" />}
                  {category === "Animals & Nature" && <span className="text-xs">🐶</span>}
                  {category === "Food & Drink" && <span className="text-xs">🍎</span>}
                  {category === "Activity" && <span className="text-xs">⚽</span>}
                  {category === "Travel & Places" && <span className="text-xs">🚗</span>}
                  {category === "Objects" && <span className="text-xs">⌚</span>}
                  {category === "Symbols" && <span className="text-xs">❤️</span>}
                </Button>
              ))}
            </div>
          </ScrollArea>
        </div>
        
        {/* Emoji Grid */}
        <div className="flex-1 p-4">
          <ScrollArea className="h-full">
            <div className="grid grid-cols-8 gap-1">
              {filteredEmojis.map((emoji, index) => (
                <Button
                  key={index}
                  variant="ghost"
                  size="sm"
                  className="h-8 w-8 p-0 text-lg hover:bg-gray-100"
                  onClick={() => handleEmojiClick(emoji)}
                >
                  {emoji}
                </Button>
              ))}
            </div>
          </ScrollArea>
        </div>
      </div>
    </div>
  )
}